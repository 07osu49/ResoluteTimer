import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import * as core from '../public/results-core.mjs';
import {placementGames,bracketGroups,bracketParticipant} from '../public/results-brackets.mjs';
const {games}=JSON.parse(readFileSync(new URL('../lib/schedule.json',import.meta.url)));
assert.equal(placementGames(games).length,14);
assert.equal(placementGames(games,'5th/6th Grade').length,0);
assert.equal(placementGames(games,'Middle School').length,3);
