assert.deepEqual(red.paths.flatMap(p=>p.edges).map(e=>[games.find(g=>g.id===e.from).code,games.find(g=>g.id===e.to).code,e.side]),[['B5','B7',1],['B6','B7',2],['B8','B9',2]]);
