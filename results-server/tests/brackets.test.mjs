const final=games.find(g=>g.division==='High School Varsity Red'&&g.code==='B7');
const feeder=games.find(g=>g.division===final.division&&g.code==='B5');
assert.equal(bracketParticipant(games,{},final,1),'Bracket Winner B5');
const results={[feeder.id]:{team1:'TEAM CLE',team2:'Gahanna',score1:16,score2:9}};
assert.equal(bracketParticipant(games,results,final,1),'TEAM CLE');
results[feeder.id].score2=16;assert.equal(bracketParticipant(games,results,final,1),'Bracket Winner B5');
results[feeder.id].score2=20;assert.equal(bracketParticipant(games,results,final,1),'Gahanna');
results[final.id]={team1:'St. Charles',team2:'St. Johns',score1:2,score2:3};
assert.equal(bracketParticipant(games,results,final,1),'St. Charles');
for(const path of red.paths)for(const edge of path.edges){const a=path.nodes.find(n=>n.game.id===edge.from),b=path.nodes.find(n=>n.game.id===edge.to);assert.ok(a.x<b.x);assert.ok(a.y>=0&&b.y>=0)}
console.log('PASS: 14 placement games, scoped winner links, graph layout, unresolved/tied games, score corrections and recorded participants.');
